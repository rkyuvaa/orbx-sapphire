export function Logo({ size = 32, className = '' }: IconProps) {
  const [theme, setTheme] = useState<'light' | 'dark'>('light');

  useEffect(() => {
    const updateTheme = () => {
      setTheme(document.documentElement.dataset.theme === 'dark' ? 'dark' : 'light');
    };
    updateTheme();
    const observer = new MutationObserver(updateTheme);
    observer.observe(document.documentElement, { attributes: true, attributeFilter: ['data-theme'] });
    return () => observer.disconnect();
  }, []);

  const imgSrc = theme === 'dark' ? '/orbx-logo-dark.svg' : '/orbx-logo-light.svg';

  return (
    <span className={`orbx-logo-wrap ${className}`} style={{ display: 'inline-flex', alignItems: 'center' }}>
      <img
        src={imgSrc}
        alt="OrbX"
        style={{ height: `${size}px`, width: 'auto', objectFit: 'contain', display: 'inline-block' }}
      />
    </span>
  );
}

